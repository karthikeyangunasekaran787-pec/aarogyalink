export const DEFAULT_LANGUAGE: Language = 'en';

export interface LanguageOption {
  code: Language;
  /** The language's own name, as a speaker expects to recognise it. */
  nativeLabel: string;
  /** The English name, used for accessible labels. */
  englishLabel: string;
}

/** The three supported languages, in selector order. English is the default. */
export const LANGUAGES: LanguageOption[] = [
  { code: 'en', nativeLabel: 'English', englishLabel: 'English' },
  { code: 'ta', nativeLabel: 'தமிழ்', englishLabel: 'Tamil' },
  { code: 'hi', nativeLabel: 'हिन्दी', englishLabel: 'Hindi' },
];

/** Narrow an arbitrary stored value to a supported language. */
export function isLanguage(value: unknown): value is Language {
  return typeof value === 'string' && LANGUAGES.some(l => l.code === value);
}

/** Values substituted into `{placeholder}` tokens. */
export type TranslationVars = Record<string, string | number>;

/**
 * Translate one key.
 *
 * - `lang` defaults to English, so a caller without a language still works.
 * - `{placeholder}` tokens are replaced from `vars` (used for counts, names and
 *   other values that must not be baked into the dictionary).
 * - A key missing from the selected language falls back to English. Every key
 *   exists in all three dictionaries (enforced by a test), so a raw key is
 *   never displayed for a key that is actually translated.
 */
export function t(key: TranslationKey, lang: Language = DEFAULT_LANGUAGE, vars?: TranslationVars): string {
  const table = translations[lang as Language] as Record<string, string> | undefined;
  const fallback = translations.en as Record<string, string>;
  const template = table?.[key] ?? fallback[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

/** Every translation key, taken from the English dictionary. */
export function translationKeys(): TranslationKey[] {
  return Object.keys(translations.en) as TranslationKey[];
}

/**
 * The language's display name in the requested UI language, e.g. "Tamil" in
 * English and "தமிழ்" at all times in the selector itself.
 */
export function languageName(code: Language): string {
  return LANGUAGES.find(l => l.code === code)?.nativeLabel ?? code;
}
